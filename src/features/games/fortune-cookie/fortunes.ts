export function drawFortunes(previous: string[] = [], random = Math.random): string[] {
  const available = fortuneLibrary.filter((fortune) => !previous.includes(fortune));
  const pool = available.length >= 3 ? available.slice() : fortuneLibrary.slice();

  for (let index = pool.length - 1; index > 0; index -= 1) {
    const other = Math.floor(random() * (index + 1));
    [pool[index], pool[other]] = [pool[other], pool[index]];
  }

  return pool.slice(0, 3);
}
